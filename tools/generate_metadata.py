"""Regenerate licensed metadata/constants from a pinned Gemstone checkout."""

from __future__ import annotations

import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path
from xml.etree import ElementTree as ET

PIN = "296d859d094347420f22415b91cfe428ff87687b"
ROOT = Path(__file__).resolve().parents[1]


def constant(name: str) -> str:
    name = name.removesuffix("Tag")
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).upper()


def main() -> None:
    checkout = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "work/reference/gemstone-pqdif"
    actual = subprocess.check_output(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"], text=True
    ).strip()
    if actual != PIN:
        raise SystemExit(f"expected reference {PIN}, got {actual}")
    # Git blobs are stable across core.autocrlf checkout policies.
    raw = subprocess.check_output(
        ["git", "-C", str(checkout), "show", PIN + ":src/Gemstone.PQDIF/TagDefinitions.xml"]
    )
    tree = ET.fromstring(raw)
    tags = [
        {child.tag: (child.text or "").strip() for child in tag}
        for tag in tree.findall("tagInfo/tag")
    ]
    identifiers = {
        group.tag: {
            (item.findtext("name") or ""): {child.tag: (child.text or "").strip() for child in item}
            for item in group
        }
        for group in tree.find("tagValues")
    }
    metadata = {
        "provenance": {
            "repository": "https://github.com/gemstone/pqdif",
            "commit": PIN,
            "source_sha256": hashlib.sha256(raw).hexdigest(),
            "license": "MIT",
            "copyright": "2019-2023 Grid Protection Alliance",
        },
        "tags": tags,
        "identifiers": identifiers,
    }
    destination = ROOT / "src/pqdif/data/registry.json"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        json.dumps(metadata, indent=2, ensure_ascii=True) + "\n", encoding="utf-8"
    )
    constants = "\n".join(f'{constant(tag["name"])} = UUID("{tag["id"]}")' for tag in tags)
    (ROOT / "src/pqdif/_tag_constants.py").write_text(
        "# Generated by tools/generate_metadata.py; GPA MIT attribution in NOTICE.\n"
        "from uuid import UUID\n\n" + constants + "\n",
        encoding="utf-8",
    )
    print(f"Generated {len(tags)} tags and {sum(map(len, identifiers.values()))} identifiers")


if __name__ == "__main__":
    main()
